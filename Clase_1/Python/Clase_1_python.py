"""## 7. Tasas: De Efectiva Anual A Mensual"""

# 7. TASAS: DE EFECTIVA ANUAL A MENSUAL

# Muchas veces una tasa esta anualizada, pero el calculo se hace mensual.
# Hay una forma aproximada y una forma financieramente equivalente.

tasa_ea = 0.25

# Forma aproximada: dividir entre 12.
tasa_mensual_aprox = tasa_ea / 12

# Forma equivalente: encontrar la tasa mensual que, capitalizada 12 meses,
# reproduce exactamente la tasa efectiva anual.
tasa_mensual_equivalente = (1 + tasa_ea) ** (1 / 12) - 1

print("\n=== TASAS MENSUALES ===")
print(f"Tasa EA: {tasa_ea:.2%}")
print(f"Tasa mensual aproximada: {tasa_mensual_aprox:.4%}")
print(f"Tasa mensual equivalente: {tasa_mensual_equivalente:.4%}")

# Diferencia de intereses en el primer mes sobre un saldo de 30 millones.
saldo = 30_000_000
interes_aprox = saldo * tasa_mensual_aprox
interes_equiv = saldo * tasa_mensual_equivalente
diferencia = interes_aprox - interes_equiv

print(f"Interes mensual aproximado: ${interes_aprox:,.0f}")
print(f"Interes mensual equivalente: ${interes_equiv:,.0f}")
print(f"Diferencia: ${diferencia:,.0f}")


# Mensaje financiero: dividir entre 12 es comun, pero no siempre correcto.
# Python ayuda a hacer la conversion exacta sin esfuerzo adicional.

"""## 8. Interes Simple"""

# 8. INTERES SIMPLE

# Formula: VF = C * (1 + i * n)
# C: capital inicial
# i: tasa por periodo
# n: numero de periodos

capital = 10_000_000
tasa_ea = 0.12
anios = 3

vf_simple = capital * (1 + tasa_ea * anios)

print("\n=== INTERES SIMPLE ===")
print(f"Capital inicial: ${capital:,.0f}")
print(f"Tasa efectiva anual: {tasa_ea:.2%}")
print(f"Plazo: {anios} años")
print(f"Valor futuro simple: ${vf_simple:,.0f}")

# En interes simple, los intereses siempre se calculan sobre el capital inicial.

"""## 9. Interes Compuesto"""

# 9. INTERES COMPUESTO

# Formula: VF = C * (1 + i) ** n
# El operador ** significa potencia.

vf_compuesto = capital * (1 + tasa_ea) ** anios

print("\n=== INTERES COMPUESTO ===")
print(f"Capital inicial: ${capital:,.0f}")
print(f"Tasa efectiva anual: {tasa_ea:.2%}")
print(f"Plazo: {anios} años")
print(f"Valor futuro compuesto: ${vf_compuesto:,.0f}")

# Diferencia entre ambos metodos.
diferencia_vf = vf_compuesto - vf_simple
print(f"Diferencia compuesto - simple: ${diferencia_vf:,.0f}")

# La diferencia puede ser pequeña en plazos cortos y enorme en plazos largos.
# Cambie anios de 3 a 20 y vuelva a ejecutar para que vean el efecto.

"""## 10. Valor Presente"""

# 10. VALOR PRESENTE

# Formula: VP = VF / (1 + i) ** n
# Sirve para traer un valor futuro al dia de hoy.

valor_futuro = 50_000_000
tasa_descuento = 0.10
anios = 5

valor_presente = valor_futuro / (1 + tasa_descuento) ** anios

print("\n=== VALOR PRESENTE ===")
print(f"Valor futuro: ${valor_futuro:,.0f}")
print(f"Tasa de descuento: {tasa_descuento:.2%}")
print(f"Plazo: {anios} años")
print(f"Valor presente: ${valor_presente:,.0f}")

# Capitalizar = llevar al futuro. Descontar = traer al presente.

