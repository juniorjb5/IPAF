"""## 12. Mini Caso Guiado: Comparar Dos Alternativas"""

# 12. MINI CASO GUIADO: COMPARAR DOS ALTERNATIVAS

# Problema:
# Un cliente tiene 20 millones para invertir durante 3 años.
# Opcion A: CDT al 9.5% efectivo anual.
# Opcion B: Fondo al 9.0% efectivo anual + bono final de $400.000.
# Pregunta: ¿cual alternativa deja mayor valor futuro?

capital = 20_000_000
plazo_anios = 3

tasa_cdt = 0.095
tasa_fondo = 0.090
bono_fondo = 400_000

vf_cdt = capital * (1 + tasa_cdt) ** plazo_anios
vf_fondo_sin_bono = capital * (1 + tasa_fondo) ** plazo_anios
vf_fondo_total = vf_fondo_sin_bono + bono_fondo

diferencia = vf_cdt - vf_fondo_total
bono_empate = vf_cdt - vf_fondo_sin_bono

print("\n=== COMPARACION DE ALTERNATIVAS ===")
print(f"Capital inicial: ${capital:,.0f}")
print(f"Plazo: {plazo_anios} años")
print(f"CDT - tasa: {tasa_cdt:.2%} | valor futuro: ${vf_cdt:,.0f}")
print(f"Fondo - tasa: {tasa_fondo:.2%} + bono ${bono_fondo:,.0f} | valor futuro: ${vf_fondo_total:,.0f}")
print(f"Diferencia CDT - Fondo: ${diferencia:,.0f}")
print(f"Bono minimo para que el fondo empate al CDT: ${bono_empate:,.0f}")

# En la sesion 2 aprenderemos a hacer que Python tome esta decision con if/else.
# Por ahora, leemos la diferencia:
# - Si diferencia > 0, el CDT gana.
# - Si diferencia < 0, el fondo gana.
# - Si diferencia = 0, empatan.


# Lectura del resultado del mini caso:
if diferencia > 0:
    print("Lectura: el CDT deja mayor valor futuro.")
elif diferencia < 0:
    print("Lectura: el fondo deja mayor valor futuro.")
else:
    print("Lectura: las dos alternativas empatan.")